CREATE TABLE "utilisateur" (
    "id_utilisateur" bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "nom"            varchar(50)  NOT NULL,
    "prenom"         varchar(50)  NOT NULL,
    "email"          varchar(100) NOT NULL UNIQUE,
    "mot_de_passe"   varchar(255) NOT NULL,          -- empreinte PBKDF2, jamais le mot de passe en clair
    "role"           varchar(20)  NOT NULL,
    "est_actif"      boolean      NOT NULL,
    "date_creation"  timestamp with time zone NOT NULL,
    -- colonnes techniques du système d'authentification de Django
    "last_login"     timestamp with time zone NULL,
    "is_superuser"   boolean      NOT NULL,
    CONSTRAINT "utilisateur_role_valide" CHECK ("role" IN ('enseignant', 'admin'))
);

-- Index pour les recherches sur l'adresse e-mail (identifiant de connexion)
CREATE INDEX "utilisateur_email_ce919624_like"
    ON "utilisateur" ("email" varchar_pattern_ops);

-- -----------------------------------------------------------------------------
-- Table lecon (entité LECON du MCD, association POSSÈDE → clé étrangère)
-- -----------------------------------------------------------------------------
CREATE TABLE "lecon" (
    "id_lecon"          bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "titre"             varchar(100) NOT NULL,
    "matiere"           varchar(50)  NOT NULL,
    "niveau_scolaire"   varchar(20)  NOT NULL,
    "contenu"           text         NOT NULL,
    "date_creation"     timestamp with time zone NOT NULL,
    "date_modification" timestamp with time zone NOT NULL,
    "id_utilisateur"    bigint       NOT NULL,
    CONSTRAINT "lecon_matiere_valide"
        CHECK ("matiere" IN ('francais', 'histoire', 'mathematiques', 'svt', 'anglais')),
    CONSTRAINT "lecon_niveau_valide"
        CHECK ("niveau_scolaire" IN ('6e', '5e', '4e', '3e'))
);

-- Une leçon appartient à un seul enseignant
ALTER TABLE "lecon"
    ADD CONSTRAINT "lecon_id_utilisateur_855000e9_fk_utilisateur_id_utilisateur"
    FOREIGN KEY ("id_utilisateur") REFERENCES "utilisateur" ("id_utilisateur")
    DEFERRABLE INITIALLY DEFERRED;

-- Index sur la clé étrangère : liste des leçons d'un enseignant
CREATE INDEX "lecon_id_utilisateur_855000e9" ON "lecon" ("id_utilisateur");

